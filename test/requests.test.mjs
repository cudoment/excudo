const line = (record) => `${JSON.stringify(record)}\n`
const claudeUser = (ts, content, extra = {}) => line({ type: "user", timestamp: ts, cwd: "/work/site", sessionId: "s1", message: { role: "user", content }, ...extra })

async function setup() {
  const logs = tempDir("excudo-logs-")
  const claude = join(logs, "claude", "-work-site")
  const codex = join(logs, "codex", "2026", "10", "13")
  mkdirSync(claude, { recursive: true })
  mkdirSync(codex, { recursive: true })
  writeFileSync(join(claude, "s1.jsonl"), [
    claudeUser("2026-10-13T01:00:00Z", "Fix the header spacing on the landing page"),
    claudeUser("2026-10-13T01:01:00Z", "<command-name>/clear</command-name>"),
    claudeUser("2026-10-13T01:02:00Z", "/compact"),
    claudeUser("2026-10-13T01:03:00Z", "Caveat: The messages below were generated by the user while running local commands."),
    claudeUser("2026-10-13T01:04:00Z", "Internal note the tool added", { isMeta: true }),
    claudeUser("2026-10-13T01:05:00Z", [{ type: "tool_result", content: "ok" }]),
    claudeUser("2026-10-13T01:06:00Z", "A subagent prompt", { isSidechain: true }),
    claudeUser("2026-10-13T01:07:00Z", [{ type: "text", text: "From now on, keep release notes short" }, { type: "image", source: {} }]),
    line({ type: "assistant", timestamp: "2026-10-13T01:08:00Z", message: { content: "Done." } }),
    claudeUser("2026-10-13T01:09:00Z", "Try this in a scratch folder", { cwd: join(tmpdir(), "scratch") }),
  ].join(""))
  writeFileSync(join(codex, "rollout.jsonl"), [
    line({ type: "session_meta", timestamp: "2026-10-13T02:00:00Z", payload: { cwd: "/elsewhere/workspaces/site/feature-x", id: "c1" } }),
    line({ type: "event_msg", timestamp: "2026-10-13T02:01:00Z", payload: { type: "user_message", message: "# Context from my IDE setup:\n## Open tabs:\n- a.md\n## My request for Codex:\nAdd a search box to the docs" } }),
    line({ type: "event_msg", timestamp: "2026-10-13T02:02:00Z", payload: { type: "agent_message", message: "Working on it" } }),
    line({ type: "session_meta", timestamp: "2026-10-13T03:00:00Z", payload: { cwd: "/somewhere/else" } }),
    line({ type: "event_msg", timestamp: "2026-10-13T03:01:00Z", payload: { type: "user_message", message: "You are a reviewer. Check the diff." } }),
    line({ type: "event_msg", timestamp: "2026-10-13T03:02:00Z", payload: { type: "user_message", message: "앞으로는 표를 쓰지 말아 줘" } }),
  ].join(""))
  const ws = await workspace({
    "projects/Site.md": "# Site\nThe website.\n\n## Workspace\n`/work/site` · `main`\n",
  }, { conversations: { claude: join(logs, "claude"), codex: join(logs, "codex") } })
  return { ws, claude: join(claude, "s1.jsonl") }
}

test("a log whose Claude Code store moved with its renamed folder is not read again", async () => {
  const { ws, claude } = await setup()
  const count = () => requests(ws, { since: "2026-10-01T00:00:00Z" }).rows.length
  const before = count()
  const root = dirname(dirname(claude))
  renameSync(join(root, "-work-site"), join(root, "-work-place"))
  ws.moved = { "/work/site": "/work/place" }
  assert.equal(count(), before, "the moved log's requests are taken once")
  appendFileSync(join(root, "-work-place", "s1.jsonl"), claudeUser("2026-10-13T04:00:00Z", "Add a footer link to the archive page", { cwd: "/work/place" }))
  assert.equal(count(), before + 1, "a request added to the moved log afterwards is taken once")
})

test("requests keep what the owner typed, attach each to the node of its folder, and stay in the cache", async () => {
  const { ws } = await setup()
  const result = requests(ws, { since: "2026-10-01T00:00:00Z" })
  assert.deepEqual(result.rows.map((row) => [row.tool, row.where, row.text]), [
    ["claude", "Site", "Fix the header spacing on the landing page"],
    ["claude", "Site", "From now on, keep release notes short"],
    ["codex", "Site", "Add a search box to the docs"],
    ["codex", "/somewhere/else", "앞으로는 표를 쓰지 말아 줘"],
  ])
  assert.equal(result.until, "2026-10-13T03:02:00Z")
  assert.deepEqual(requests(ws, { since: "2026-10-01T00:00:00Z", candidates: true }).rows.map((row) => row.text),
    ["From now on, keep release notes short", "앞으로는 표를 쓰지 말아 줘"])
  // The text lives in the workspace cache only.
  assert.ok(existsSync(join(ws.cacheDir, "records.db")))
  assert.ok(!readdirSync(ws.graphDir, { recursive: true }).some((file) => String(file).includes("request")))
})

test("what a scheduled run typed is no request of the owner's, even once its log grows", async () => {
  const { ws, claude } = await setup()
  const run = join(claude, "..", "run.jsonl")
  writeFileSync(run, claudeUser("2026-10-13T04:00:00Z", "Reflect on the requests since the last mark", { sessionId: "r1", entrypoint: "sdk-cli" }))
  const texts = () => requests(ws, { since: "2026-10-01T00:00:00Z" }).rows.map((row) => row.text)
  assert.ok(!texts().includes("Reflect on the requests since the last mark"))
  // A later line of the same session without the marker is still the run's.
  appendFileSync(run, claudeUser("2026-10-13T04:05:00Z", "Then save the reflection", { sessionId: "r1" }))
  assert.ok(!texts().includes("Then save the reflection"))
  assert.ok(texts().includes("Fix the header spacing on the landing page"))
})

test("marks are per purpose, and a request added to a log is taken once", async () => {
  const { ws, claude } = await setup()
  assert.equal(requests(ws, { now: new Date("2026-10-14T00:00:00Z") }).rows.length, 4, "without a mark, the last week")
  assert.equal(markRequests(ws, "cleanup"), "2026-10-13T03:02:00Z")
  assert.equal(requests(ws).rows.length, 0)
  assert.equal(requests(ws, { purpose: "reflect", now: new Date("2026-10-14T00:00:00Z") }).rows.length, 4)
  appendFileSync(claude, claudeUser("2026-10-13T04:00:00Z", "Ship the landing page today"))
  assert.deepEqual(requests(ws).rows.map((row) => row.text), ["Ship the landing page today"])
  markRequests(ws, "reflect", { until: "2026-10-13T01:30:00Z" })
  assert.deepEqual(requests(ws, { purpose: "reflect" }).rows.map((row) => row.text),
    ["Add a search box to the docs", "앞으로는 표를 쓰지 말아 줘", "Ship the landing page today"])
  assert.throws(() => requests(ws, { purpose: "later" }), /cleanup or reflect/)
})

test("reading requests is off unless the workspace turns it on, and the command prints one line per request", async () => {
  const off = await workspace({ "projects/Site.md": "# Site\nThe website.\n" })
  assert.throws(() => requests(off), /conversations: true/)
  const { ws } = await setup()
  const cli = (...args) => spawnSync(process.execPath, [resolve("bin/excudo.mjs"), "--root", ws.root, ...args], { encoding: "utf8" })
  const out = cli("requests", "--since", "2026-10-01T00:00:00Z").stdout
  assert.match(out, /^4 requests after 2026-10-01T00:00:00\.000Z for cleanup$/m)
  assert.match(out, /^\d\d-\d\d \d\d:\d\d {2}\[Site\] Fix the header spacing on the landing page$/m)
  assert.match(out, /requests mark --for cleanup --until 2026-10-13T03:02:00Z/)
  assert.match(cli("requests", "mark", "--for", "reflect").stderr, /list the requests first/)
  cli("requests", "--for", "reflect", "--since", "2026-10-01T00:00:00Z")
  assert.match(cli("requests", "mark", "--for", "reflect").stdout, /up to 2026-10-13T03:02:00Z are marked read for reflection/)
  assert.notEqual(cli("requests", "mark").status, 0)
})

test("Codex logs are read in each format they were written in, without the injected instructions or duplicates", async () => {
  const logs = tempDir("excudo-codex-")
  const day = join(logs, "2026", "10", "13")
  mkdirSync(day, { recursive: true })
  const meta = (cwd) => line({ type: "session_meta", timestamp: "2026-10-13T05:00:00Z", payload: { cwd } })
  const item = (ts, text) => line({ type: "response_item", timestamp: ts, payload: { type: "message", role: "user", content: [{ type: "input_text", text }] } })
  // A current log: the typed request is a completed UserMessage item and also a response item.
  writeFileSync(join(day, "rollout-new.jsonl"), [
    meta("/work/site"),
    item("2026-10-13T05:00:01Z", "# AGENTS.md instructions for /work/site\n\n<INSTRUCTIONS>\nBe brief.\n</INSTRUCTIONS>"),
    item("2026-10-13T05:01:00Z", "Review the open branch"),
    line({ type: "event_msg", timestamp: "2026-10-13T05:01:00Z", payload: { type: "item_completed", item: { type: "UserMessage", content: [{ type: "text", text: "Review the open branch" }] } } }),
    line({ type: "turn_context", timestamp: "2026-10-13T05:02:00Z", payload: { cwd: "/work/site/docs" } }),
    line({ type: "event_msg", timestamp: "2026-10-13T05:03:00Z", payload: { type: "item_completed", item: { type: "UserMessage", content: [{ type: "text", text: "Then fix the docs" }] } } }),
  ].join(""))
  // An older log has only response items for what the owner typed.
  writeFileSync(join(day, "rollout-old.jsonl"), [
    meta("/work/site"),
    item("2026-10-13T06:00:00Z", "# AGENTS.md instructions for /work/site\n\n<INSTRUCTIONS>\nBe brief.\n</INSTRUCTIONS>"),
    item("2026-10-13T06:00:01Z", "<environment_context>\n  <cwd>/work/site</cwd>\n</environment_context>"),
    item("2026-10-13T06:01:00Z", "Summarize yesterday's changes"),
  ].join(""))
  const ws = await workspace({ "projects/Site.md": "# Site\nThe website.\n\n- `/work/site` · `main`\n" },
    { conversations: { claude: false, codex: logs } })
  assert.deepEqual(requests(ws, { since: "2026-10-01T00:00:00Z" }).rows.map((row) => [row.where, row.cwd, row.text]), [
    ["Site", "/work/site", "Review the open branch"],
    ["Site", "/work/site/docs", "Then fix the docs"],
    ["Site", "/work/site", "Summarize yesterday's changes"],
  ])
})

test("a voice session's handover keeps only the owner's words, and its closing tail is no request", async () => {
  const logs = tempDir("excudo-codex-")
  const day = join(logs, "2026", "10", "13")
  mkdirSync(day, { recursive: true })
  const said = (ts, text) => line({ type: "event_msg", timestamp: ts, payload: { type: "item_completed", item: { type: "UserMessage", content: [{ type: "text", text }] } } })
  const talk = "assistant: Sure, I can help you sort your thoughts, or work on docs, code and plans with you.\nuser: "
  const handed = (input, source) => `<realtime_delegation>\n${source ? `  <source>${source}</source>\n` : ""}  <input>${input}</input>\n  <transcript_delta>${talk}${input}</transcript_delta>\n</realtime_delegation>`
  const tail = handed("The user just ended their realtime session. Here is the remaining handoff/transcript tail. You probably do not have to do anything; acknowledge the handoff unless the transcript itself asks for something.", "transcript_tail_flush")
  const asked = ["Check what changed in the docs today", "Draft a plan for the release", "Look for another project with this name"]
  asked.forEach((input, i) => writeFileSync(join(day, `rollout-voice-${i}.jsonl`), [
    line({ type: "session_meta", timestamp: `2026-10-13T0${i + 1}:00:00Z`, payload: { cwd: "/work/site" } }),
    said(`2026-10-13T0${i + 1}:01:00Z`, handed(input)),
    said(`2026-10-13T0${i + 1}:02:00Z`, tail),
  ].join("")))
  const ws = await workspace({ "projects/Site.md": "# Site\nThe website.\n\n- `/work/site` · `main`\n" },
    { conversations: { claude: false, codex: logs } })
  assert.deepEqual(requests(ws, { since: "2026-10-01T00:00:00Z" }).rows.map((row) => row.text), asked)
  // The envelope and the voice model's replies made unrelated requests and every closing tail look alike.
  assert.deepEqual(skillCandidates(ws, { now: new Date("2026-10-14T00:00:00Z") }).candidates, [])
})

test("a Codex log read mid-turn or resumed in a newer format keeps each request once", async () => {
  const logs = tempDir("excudo-codex-")
  const day = join(logs, "2026", "10", "13")
  mkdirSync(day, { recursive: true })
  const file = join(day, "rollout-resumed.jsonl")
  const item = (ts, text) => line({ type: "response_item", timestamp: ts, payload: { type: "message", role: "user", content: [{ type: "input_text", text }] } })
  writeFileSync(file, [
    line({ type: "session_meta", timestamp: "2026-10-13T05:00:00Z", payload: { cwd: "/work/site" } }),
    item("2026-10-13T05:01:00Z", "Summarize yesterday's changes"),
  ].join(""))
  const ws = await workspace({ "projects/Site.md": "# Site\nThe website.\n\n- `/work/site` · `main`\n" },
    { conversations: { claude: false, codex: logs } })
  const texts = () => requests(ws, { since: "2026-10-01T00:00:00Z" }).rows.map((row) => row.text)
  assert.deepEqual(texts(), ["Summarize yesterday's changes"])
  appendFileSync(file, [
    item("2026-10-13T06:01:00Z", "Then draft the notice"),
    line({ type: "event_msg", timestamp: "2026-10-13T06:01:00Z", payload: { type: "item_completed", item: { type: "UserMessage", content: [{ type: "text", text: "Then draft the notice" }] } } }),
  ].join(""))
  assert.deepEqual(texts(), ["Summarize yesterday's changes", "Then draft the notice"])
  assert.deepEqual(texts(), ["Summarize yesterday's changes", "Then draft the notice"])
  // Read between a request's response item and its event, which Codex writes right after.
  const live = join(day, "rollout-live.jsonl")
  writeFileSync(live, [
    line({ type: "session_meta", timestamp: "2026-10-13T07:00:00Z", payload: { cwd: "/work/site" } }),
    item("2026-10-13T07:01:00Z", "Check the build output"),
  ].join(""))
  assert.equal(texts().length, 3)
  appendFileSync(live, [
    line({ type: "event_msg", timestamp: "2026-10-13T07:01:00Z", payload: { type: "item_completed", item: { type: "UserMessage", content: [{ type: "text", text: "Check the build output" }] } } }),
    item("2026-10-13T07:02:00Z", "Ship it after the check"),
    line({ type: "event_msg", timestamp: "2026-10-13T07:02:00Z", payload: { type: "item_completed", item: { type: "UserMessage", content: [{ type: "text", text: "Ship it after the check" }] } } }),
  ].join(""))
  assert.deepEqual(texts().slice(2), ["Check the build output", "Ship it after the check"])
})

test("request text never goes where the graph syncs or git commits it", async () => {
  const logs = tempDir("excudo-logs-")
  mkdirSync(join(logs, "-site"))
  writeFileSync(join(logs, "-site", "s.jsonl"), claudeUser("2026-10-13T01:00:00Z", "Fix the header spacing"))
  const inGraph = await workspace({ "projects/Site.md": "# Site\nThe website.\n" }, { cache: "notes/.cache", conversations: { claude: logs, codex: false } })
  assert.throws(() => requests(inGraph), /inside the graph or not ignored by git/)
  const tracked = await workspace({ "projects/Site.md": "# Site\nThe website.\n" }, { conversations: { claude: logs, codex: false } })
  spawnSync("git", ["-C", tracked.root, "init", "-q"])
  assert.throws(() => requests(tracked), /not ignored by git/)
  // A workspace outside git is judged by the repository its cache lands in, also through a link.
  const other = tempDir("excudo-repo-")
  spawnSync("git", ["-C", other, "init", "-q"])
  const away = await workspace({ "projects/Site.md": "# Site\nThe website.\n" }, { cache: join(other, "cache"), conversations: { claude: logs, codex: false } })
  assert.throws(() => requests(away), /not ignored by git/)
  writeFileSync(join(other, ".gitignore"), "cache/\n")
  assert.equal(requests(away, { since: "2026-10-01T00:00:00Z" }).rows.length, 1)
  const linked = await workspace({ "projects/Site.md": "# Site\nThe website.\n" }, { conversations: { claude: logs, codex: false } })
  mkdirSync(join(other, "linked"))
  symlinkSync(join(other, "linked"), join(linked.root, ".excudo"), "dir")
  assert.throws(() => requests(linked), /not ignored by git/)
  assert.ok(!existsSync(join(other, "linked", "records.db")))
  writeFileSync(join(tracked.root, ".gitignore"), ".excudo/\n")
  assert.equal(requests(tracked, { since: "2026-10-01T00:00:00Z" }).rows.length, 1)
  // A folder excluded after its requests were cached stays out as well.
  const excluding = { ...tracked, conversations: { claude: logs, codex: false, exclude: ["/work/site"] } }
  assert.equal(requests(excluding, { since: "2026-10-01T00:00:00Z" }).rows.length, 0)
})

test("folders map to nodes by path, by worktrees of the same repository, and only by an exact folder name when gone", async () => {
  const repo = tempDir("excudo-site-")
  const run = (...args) => assert.equal(spawnSync("git", ["-C", repo, "-c", "user.name=t", "-c", "user.email=t@example.com", ...args]).status, 0)
  run("init", "-q", "-b", "main")
  writeFileSync(join(repo, "a.md"), "a\n")
  run("add", ".")
  run("commit", "-qm", "Start")
  const worktree = join(tempDir("excudo-wt-"), "feature")
  run("worktree", "add", "-q", "-b", "feature", worktree)
  const name = repo.split("/").pop()
  const ws = await workspace({ "projects/Site.md": `# Site\nThe website.\n\n- \`${repo}\` · \`main\`\n` })
  assert.deepEqual([worktree, `${repo}/src`, `/gone/workspaces/${name}/feature-y`, `/unrelated/${name}-backup`].map((cwd) => folderPlace(ws, cwd).where),
    ["Site", "Site", "Site", `/unrelated/${name}-backup`])

  // A folder two pieces of work share below one parent: its requests belong to the parent.
  put(ws.root, "projects/Site/Search.md", `# Search\nBetter search.\n\n- \`${repo}\` · \`main\` · windows: test set\n`)
  put(ws.root, "projects/Site/Data.md", `# Data\nTest data.\n\n- \`${repo}\` · \`main\`\n`)
  put(ws.root, "projects/Site.md", "# Site\nThe website.\n")
  assert.equal(folderPlace(ws, `${repo}/src`).where, "Site")
})

test("marking without a time marks only what the last listing considered", async () => {
  const { ws, claude } = await setup()
  const shown = requests(ws, { since: "2026-10-01T00:00:00Z" })
  appendFileSync(claude, claudeUser("2026-10-13T05:00:00Z", "Arrived while tidying"))
  assert.equal(markRequests(ws, "cleanup"), shown.until)
  assert.deepEqual(requests(ws).rows.map((row) => row.text), ["Arrived while tidying"])
  assert.throws(() => markRequests(ws, "reflect"), /list the requests first/)
})

test("a long JSON answer reaches a pipe whole", async () => {
  const logs = tempDir("excudo-logs-")
  mkdirSync(join(logs, "-site"))
  const long = "Please keep this request in full. ".repeat(20)
  writeFileSync(join(logs, "-site", "s.jsonl"), Array.from({ length: 400 }, (_, i) =>
    claudeUser(`2026-10-13T${String(Math.floor(i / 60)).padStart(2, "0")}:${String(i % 60).padStart(2, "0")}:00Z`, `${i} ${long}`)).join(""))
  const ws = await workspace({ "projects/Site.md": "# Site\nThe website.\n" }, { conversations: { claude: logs, codex: false } })
  const result = spawnSync(process.execPath, [resolve("bin/excudo.mjs"), "--root", ws.root, "requests", "--json", "--since", "2026-10-01T00:00:00Z"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
  assert.ok(result.stdout.length > 200000)
  assert.equal(JSON.parse(result.stdout).rows.length, 400)
})
