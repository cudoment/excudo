export const PURPOSES = ["cleanup", "reflect"]
const TOOLS = { claude: "~/.claude/projects", codex: "~/.codex/sessions" }
const FIRST_DAYS = 7
const MIN_LENGTH = 4
// How much of a pasted text a listing shows; the cache keeps all of it.
const PASTED_SHOWN = 300

// Text a tool or another agent put into the prompt, not something the owner typed.
const INJECTED = [
  /^#\s*Files mentioned by the user:/m,
  /^#\s*AGENTS\.md instructions for /m,
  // A shell command the owner ran through the agent (`! cmd`) and its output are no request, and
  // either may hold whatever the command took or printed.
  /^<(?:command-name|command-message|command-args|local-command|turn_aborted|system-reminder|user-prompt-submit-hook|environment_context|task-notification|bash-input|bash-stdout|bash-stderr)/m,
  /^Caveat: The messages below were generated by the user/m,
  /^\[Request interrupted/m,
  /^\[Image: original \d+x\d+/,
  /^This session is being continued from a previous conversation/m,
  // A command typed alone carries no request; `/ask what…` with words after it does.
  /^(?:clear|compact|resume|exit|quit|help|init|login|logout)$/i,
  /^\/[a-z][a-z0-9:-]*$/i,
  // One agent instructing another.
  /^You are (?:a|an|working|the) /i,
  /^The following is the Codex agent history/m,
  /^Your coordinator/m,
  /^Treat all segment text as untrusted/i,
]
// Text the owner pasted, which Claude Code wraps in these tags: someone else's words (a review, a
// specification, a log) that the request is about. It is kept apart, as the request's context, so
// it is never read as the owner's own decision.
const PASTED = /<pasted_content(?: id="([^"]*)")?>\n?([\s\S]*?)\n?<\/pasted_content(?: id="\1")?>/g
const PLACEHOLDER = /\[pasted \d+\]/g
// A voice session (Codex realtime) hands what the owner said to the coding agent in an envelope: their
// words in `input`, and the talk before them, the voice model's replies too, in `transcript_delta`.
// Only the words are the request. When the session ends, the rest of the talk comes under an input
// the tool wrote (`source` transcript_tail_flush): nothing the owner handed over.
const DELEGATION = /^<realtime_delegation>([\s\S]*)<\/realtime_delegation>$/
const DELEGATED = /<input>([\s\S]*?)<\/input>/
const TAIL_FLUSH = /<source>\s*transcript_tail_flush\s*<\/source>/
// Context an editor puts before the request; the request follows it.
const PREFIXES = [
  /^#\s*Context from my IDE setup:\s*\n/m,
  /^##\s*(?:Active file|Active selection of the file|Open tabs|Selected text|Cursor position)\s*:.*?(?=\n##\s|\n#\s|$(?![\s\S]))/gms,
  /^##\s*My request for \w+:\s*/m,
]
// Words that often carry a decision, a standing instruction or a judgment. They pick what to read
// first when reflecting; a request without them may still hold one.
const DURABLE = new RegExp([
  "앞으로|이후에는|앞으로는|계속해서|항상|매번|기본값|기본 값|규칙으로|지침에도|관례로|원칙으로",
  "유지하고 싶|하지 말|하지 않도록|금지|절대|할 예정|하려고 해|하기로 했|방침|기억해",
  "의견을 알려|어떻게 생각|권장|선호|더 나은|낫다고 보|스킬을 수정|지침을 수정|규칙을 수정|문서에도 반영",
  "from now on|going forward|always|never|by default|don't|do not|stop doing|remember|prefer|instead of|rule",
].join("|"), "i")

/** Where the logs are, or null when reading them is off (the default). */
export function conversationsOf(ws) {
  const setting = ws.conversations
  if (!setting) return null
  const given = setting === true ? {} : setting
  const tool = (name) => given[name] === false ? null : localPath(ws, given[name] ?? TOOLS[name])
  return { claude: tool("claude"), codex: tool("codex"), exclude: (given.exclude ?? []).map((path) => localPath(ws, path)) }
}

/**
 * The owner's words of a typed request, with each pasted text replaced by `[pasted N]` and listed in
 * `pasted` (numbered after the ones given), or undefined when it is no request.
 */
function clean(value, given = []) {
  if (typeof value !== "string") return undefined
  const envelope = value.trim().match(DELEGATION)
  if (envelope) {
    if (TAIL_FLUSH.test(envelope[1])) return undefined
    value = envelope[1].match(DELEGATED)?.[1] ?? ""
  }
  const pasted = [...given]
  let text = value.replace(PASTED, (_, id, body) => { pasted.push(body.trim()); return `[pasted ${pasted.length}]` })
  for (const prefix of PREFIXES) text = text.replace(prefix, "")
  text = text.trim()
  if (INJECTED.some((rule) => rule.test(text))) return undefined
  // A paste alone is still a request: the owner handed it over.
  if ([...text.replace(PLACEHOLDER, "").trim()].length < MIN_LENGTH && !pasted.some(Boolean)) return undefined
  return pasted.length ? { text, pasted } : { text }
}

/** Folders where no person works: temporary folders and app data. */
export function skippedFolder(cwd, exclude) {
  if (!cwd) return false
  const home = homedir()
  const temp = [tmpdir(), real(tmpdir()), "/private/var/folders", "/private/tmp", "/tmp", join(home, "Library", "Application Support"), join(home, "Library", "Caches")]
  return [...temp, ...exclude].some((root) => cwd === root || cwd.startsWith(root.endsWith(sep) ? root : root + sep))
}

function claudeRequests(path) {
  const requests = []
  const batch = new Set()
  for (const line of readFileSync(path, "utf8").split("\n")) {
    let record
    try { record = JSON.parse(line) } catch { continue }
    // A scheduled run (`claude -p`) types its own prompt: what it asks is no request of the owner's.
    if (record.entrypoint === "sdk-cli") { if (record.sessionId) batch.add(record.sessionId); continue }
    if (record.type !== "user" || record.isMeta || record.isSidechain) continue
    let content = record.message?.content
    // Tool results arrive as lists; a typed request is a string, or text next to an attached image.
    if (Array.isArray(content)) {
      if (content.some((block) => block?.type !== "text" && block?.type !== "image")) continue
      content = content.filter((block) => block.type === "text").map((block) => block.text).join("\n")
    }
    const found = clean(content)
    if (found) requests.push({ ts: record.timestamp, cwd: record.cwd, session: record.sessionId, ...found })
  }
  // A line of a scheduled session that does not carry the marker is still the run's.
  return { shape: "claude", requests: requests.filter((request) => !batch.has(request.session)), batch }
}

// Codex has written a typed request three ways: an older `user_message` event, a newer completed
// `UserMessage` item, and in every version a user `message` response item, which also carries the
// injected instructions and context. The response items are read only when a log has neither event;
// `shape` says which were read, since a session resumed in a newer Codex can switch.
const codexText = (blocks) => Array.isArray(blocks) ? blocks.filter((block) => typeof block?.text === "string").map((block) => block.text).join("\n") : blocks
function codexRequests(path) {
  const records = []
  for (const line of readFileSync(path, "utf8").split("\n")) { try { records.push(JSON.parse(line)) } catch {} }
  const typed = (record) => record.type === "event_msg" && (record.payload?.type === "user_message" || record.payload?.type === "item_completed" && record.payload.item?.type === "UserMessage")
  const events = records.some(typed)
  const requests = []
  let cwd
  for (const record of records) {
    const payload = record.payload ?? {}
    if (record.type === "session_meta" || record.type === "turn_context") { cwd = payload.cwd ?? cwd; continue }
    let value
    if (events && typed(record)) value = payload.type === "user_message" ? payload.message : codexText(payload.item.content)
    else if (!events && record.type === "response_item" && payload.type === "message" && payload.role === "user") value = codexText(payload.content)
    else continue
    const found = clean(value)
    if (found) requests.push({ ts: record.timestamp, cwd, session: basename(path, ".jsonl"), ...found })
  }
  return { shape: events ? "events" : "responses", requests }
}

function logFiles(dir) {
  const files = []
  const walk = (at) => {
    let entries
    // A folder that went away is no log; one that cannot be read leaves requests unread, and says so.
    try { entries = readdirSync(at, { withFileTypes: true }) } catch (error) { if (error.code === "ENOENT" || error.code === "ENOTDIR") return; throw error }
    for (const entry of entries) {
      const full = join(at, entry.name)
      if (entry.isDirectory()) walk(full)
      else if (entry.isFile() && entry.name.endsWith(".jsonl")) files.push(full)
    }
  }
  if (dir && existsSync(dir)) walk(dir)
  return files.sort()
}

// Raised when extraction changes, so the cache is read again from the logs; marks are kept. A request
// whose log the agent has since deleted is not lost: its cached row is cleaned again instead.
const EXTRACTION = 6
export { checkCache }

const cursorOf = (db, path) => db.prepare("SELECT size, mtime, count, shape FROM cursors WHERE kind = 'requests' AND path = ?").get(path)

/** The folder Claude Code keeps a working folder's transcripts in, under its projects folder. */
export const claudeStore = (folder) => folder.replace(/[^A-Za-z0-9]/g, "-")
/**
 * Where a Claude Code log was read before its folder was renamed: the store is named after the folder,
 * so a store moved along with its folder (the `moved` setting) holds the same logs under a new name.
 * Its cursor is found there, and the requests already taken from it are not taken again.
 */
function earlierLogs(ws, root, path) {
  if (!root || !path.startsWith(`${root}/`)) return []
  const [store, ...rest] = path.slice(root.length + 1).split("/")
  let moves
  try { moves = movedFolders(ws) } catch { return [] }
  return moves.filter(([, to]) => claudeStore(movedPath(moves, to)) === store).map(([from]) => join(root, claudeStore(from), ...rest))
}
const setCursor = (db, path, mark) => db.prepare(`INSERT INTO cursors (kind, path, size, mtime, count, shape) VALUES ('requests', ?, ?, ?, ?, ?)
  ON CONFLICT (kind, path) DO UPDATE SET size = excluded.size, mtime = excluded.mtime, count = excluded.count, shape = excluded.shape`).run(path, mark.size, mark.mtime, mark.count, mark.shape)

function collect(ws, db) {
  const where = conversationsOf(ws)
  if (!where) throw new Error(ws.labels.messages["requests-off"])
  // A new extraction reads every log again. The rows are replaced in the same transaction, so a
  // failure on the way leaves them, and the requests whose log is gone, as they were.
  const migrating = setting(db, "requests.extraction") !== EXTRACTION
  const earlier = migrating ? requestRecords(db) : []
  if (migrating) db.exec("DELETE FROM cursors WHERE kind = 'requests'")
  let added = 0
  const rows = []
  const batch = new Set()
  const keyOf = (row) => `${row.tool}|${row.session}|${row.ts}`
  for (const [tool, read] of [["claude", claudeRequests], ["codex", codexRequests]]) {
    for (const path of logFiles(where[tool])) {
      let stat
      try { stat = statSync(path) } catch { continue }
      let mark = cursorOf(db, path)
      const earlier = mark || tool !== "claude" ? undefined : earlierLogs(ws, where.claude, path).find((old) => cursorOf(db, old))
      if (earlier) {
        mark = cursorOf(db, earlier)
        db.prepare("UPDATE cursors SET path = ? WHERE kind = 'requests' AND path = ?").run(path, earlier)
      }
      if (mark && mark.size === stat.size && mark.mtime === Math.floor(stat.mtimeMs)) continue
      // A changed log is parsed again; the requests already taken from it are skipped by count. When
      // the log switched how it records requests, the count no longer lines up: they are matched by text.
      const { shape, requests: found, batch: scheduled } = read(path)
      for (const session of scheduled ?? []) batch.add(session)
      const taken = mark?.shape === shape ? mark.count : 0
      const known = new Map()
      // Two requests with the same words around different pastes are different requests.
      const signature = (request) => `${request.text}\u0000${JSON.stringify(request.pasted ?? [])}`
      if (mark && mark.shape !== shape) {
        const sessions = new Set(found.map((request) => request.session ?? null))
        for (const row of requestRecords(db)) if (row.tool === tool && sessions.has(row.session)) known.set(signature(row), (known.get(signature(row)) ?? 0) + 1)
      }
      found.forEach((request, i) => {
        if (i < taken || skippedFolder(request.cwd, where.exclude)) return
        if (known.get(signature(request))) { known.set(signature(request), known.get(signature(request)) - 1); return }
        rows.push({ ts: request.ts, tool, cwd: request.cwd ?? null, session: request.session ?? null, text: request.text, ...(request.pasted ? { pasted: request.pasted } : {}) })
        added++
      })
      setCursor(db, path, { size: stat.size, mtime: Math.floor(stat.mtimeMs), count: found.length, shape })
    }
  }
  if (migrating) {
    const read = new Set(rows.map(keyOf))
    for (const row of earlier) {
      if (read.has(keyOf(row)) || skippedFolder(row.cwd, where.exclude) || batch.has(row.session)) continue
      const found = clean(row.text, row.pasted)
      if (found) rows.push({ ts: row.ts, tool: row.tool, cwd: row.cwd, session: row.session, ...found })
    }
    db.exec("DELETE FROM requests")
    setSetting(db, "requests.extraction", EXTRACTION)
  }
  insertRequests(db, rows)
  return added
}

/** Reads new requests from the logs into the records; a log file whose size and time are unchanged is not opened. */
export function collectRequests(ws) {
  return withRecords(ws, (db) => collect(ws, db), { write: true })
}

// A folder reached through a link (a renamed folder left as a link) is compared by where it leads.
const real = (path) => { try { return realpathSync(path) } catch { return path } }
const commonDirs = new Map()
/** The repository a folder belongs to, shared by all its worktrees. */
function commonDir(path) {
  if (!commonDirs.has(path)) {
    const result = spawnSync("git", ["-C", path, "rev-parse", "--path-format=absolute", "--git-common-dir"], { encoding: "utf8" })
    commonDirs.set(path, result.status === 0 ? real(result.stdout.trim()) : undefined)
  }
  return commonDirs.get(path)
}

/**
 * Folder → node: path lines first, then the folders of repository sources and their old paths. A
 * folder renamed since (the `moved` setting) is read where it is now; one the owner does not track
 * in the memo is marked as such.
 */
function placesOf(ws, given) {
  const moves = movedFolders(ws)
  const untracked = untrackedFolders(ws)
  const known = { moves, untracked, list: [] }
  let model = given
  if (!model) try { model = prepare(ws).model } catch { return known }
  // A path line or a repository may still name a folder by its old path; it is read where it is now.
  const at = (path) => real(movedPath(moves, path))
  const byPath = new Map()
  for (const line of pathLines(ws, { model })) byPath.set(at(line.path), [...byPath.get(at(line.path)) ?? [], line])
  // A request typed in a folder several nodes share belongs to the work they share: their parent.
  const places = [...byPath].map(([path, lines]) => {
    const nodes = [...new Set(lines.map((line) => line.node))]
    const parent = nodes.length > 1 ? sharedParent(model, nodes) : ROOT
    return { path, node: parent === ROOT ? lines[0].name : pageOf(parent) }
  })
  for (const source of sourcesOf(ws)) if (source.kind === "repo" && source.node)
    for (const path of [source.path, ...source.aliases]) places.push({ path: at(path), node: source.node })
  known.list = places.sort((a, b) => b.path.length - a.path.length)
  return known
}

function whereOf(cwd, known) {
  if (!cwd) return { where: "?" }
  const now = movedPath(known.moves, cwd)
  const placed = placeOf(now, known.list)
  if (placed) return placed
  const home = homedir()
  return { where: now === home ? "~" : now.startsWith(home + "/") ? `~/${now.slice(home.length + 1)}` : now,
    ...(known.untracked.some((folder) => within(now, folder) || within(real(now), real(folder))) ? { untracked: true } : {}) }
}

function placeOf(cwd, places) {
  const at = real(cwd)
  const hit = places.find((place) => within(at, place.path))
  if (hit) return { node: hit.node, where: hit.node }
  // Another worktree of a known repository belongs to the repository's node. A worktree that is
  // gone counts only when a folder on its path has exactly the repository's folder name.
  if (existsSync(at)) {
    const common = commonDir(at)
    const same = common && places.find((place) => existsSync(place.path) && commonDir(place.path) === common)
    if (same) return { node: same.node, where: same.node }
  } else {
    const parts = at.split("/")
    for (let i = parts.length - 1; i > 0; i--) {
      const named = places.find((place) => basename(place.path) === parts[i])
      if (named) return { node: named.node, where: named.node }
    }
  }
  return undefined
}

/** The node a folder's requests belong to, or a short label for a folder no node claims. */
export function folderPlace(ws, cwd) {
  return whereOf(cwd, placesOf(ws))
}

/** Places many folders at the cost of one: the nodes are read once, or taken from `model`. */
export function placer(ws, { model } = {}) {
  const known = placesOf(ws, model)
  return (cwd) => whereOf(cwd, known)
}

/** The marks and the newest request each purpose's last listing considered. */
export function requestState(ws) {
  return withRecords(ws, (db) => ({ marks: (db && setting(db, "requests.marks")) ?? {}, shown: (db && setting(db, "requests.shown")) ?? {} }))
}

const byTime = (a, b) => (a.ts < b.ts ? -1 : a.ts > b.ts ? 1 : 0)

/**
 * The cached requests after `since` (an ISO time), oldest first, read fresh from the logs. Each row
 * keeps its pasted texts; `key` identifies it without its words, so a record in git can name it.
 */
export function requestRows(ws, { since, refresh = true } = {}) {
  const where = conversationsOf(ws)
  if (!where) throw new Error(ws.labels.messages["requests-off"])
  return withRecords(ws, (db) => {
    if (refresh) collect(ws, db)
    const after = since ? new Date(since).getTime() : 0
    return requestRecords(db, { after }).filter((row) => !skippedFolder(row.cwd, where.exclude))
      .sort(byTime).map((row) => ({ ...row, key: requestKey(row) }))
  }, { write: refresh })
}
export const requestKey = (row) => `${row.tool}|${row.session}|${row.ts}`

// A passage this long, copied from a request, is the request's words rather than a summary of them.
// Windows start at words and must read as prose: a command or a path the owner typed is no leak.
export const COPIED_LENGTH = 32
const flat = (text) => text.normalize("NFC").replace(PLACEHOLDER, " ").replace(/\s+/g, " ").trim()
const prose = (window) => (window.match(/\p{L}/gu) ?? []).length >= COPIED_LENGTH / 2 && (window.match(/[-/._=`$#{}()<>:\\|*[\]"]/g) ?? []).length <= 2
function eachWindow(chars, fn) {
  for (let i = 0; i + COPIED_LENGTH <= chars.length; i++) {
    if (i && chars[i - 1] !== " ") continue
    const window = chars.slice(i, i + COPIED_LENGTH).join("")
    if (prose(window)) fn(window, i)
  }
}

/** Every string value of a JSON text, or undefined when it is no JSON. */
export function jsonValues(text) {
  let value
  try { value = JSON.parse(text) } catch { return undefined }
  const strings = []
  const walk = (item) => {
    if (typeof item === "string") strings.push(item)
    else if (Array.isArray(item)) item.forEach(walk)
    else if (item && typeof item === "object") Object.values(item).forEach(walk)
  }
  walk(value)
  return strings
}
/** The string values of a JSON text, one per line, or undefined when it is no JSON. */
export const jsonStrings = (text) => jsonValues(text)?.join("\n")

/**
 * The owner's own words in the cached requests, as the windows `copiedPassages` compares; null when
 * requests are not read. What they pasted is left out: it is often the memo or a skill itself, which
 * would then read as copied from a request.
 */
export function requestWindows(ws) {
  if (!conversationsOf(ws)) return null
  return withRecords(ws, (db) => {
    if (!db) return null
    const seen = new Set()
    for (const row of requestRecords(db)) eachWindow([...flat(row.text ?? "")], (window) => seen.add(window))
    return seen
  })
}

/**
 * The passages of `items` ({ file, text }) copied from the requests the owner typed, at most five
 * per file, or null when this workspace does not read requests. The requests themselves stay in the
 * cache; only an agent sees the passages, so it can say them in its own words.
 */
export function copiedPassages(ws, items, seen = requestWindows(ws)) {
  if (!seen) return null
  const found = []
  for (const { file, text } of items) {
    // JSON keeps line breaks and quotes escaped; its strings are compared as they read.
    const chars = [...flat(file.endsWith(".json") ? jsonStrings(text) ?? text : text)]
    // Overlapping windows of one copied stretch are reported as that stretch.
    const ranges = []
    eachWindow(chars, (window, at) => {
      if (!seen.has(window)) return
      const last = ranges.at(-1)
      if (last && at <= last[1]) last[1] = at + COPIED_LENGTH
      else ranges.push([at, at + COPIED_LENGTH])
    })
    for (const [from, to] of ranges.slice(0, 5)) found.push({ file, passage: chars.slice(from, to).join("") })
  }
  return found
}

/**
 * The requests after the mark of `purpose` ("cleanup" or "reflect"), oldest first, each with the
 * node its folder belongs to. Without a mark, the last week. `candidates` keeps the ones whose
 * words suggest a lasting decision. `until` is the newest request considered, candidate or not:
 * marking up to it never skips one that was not shown.
 */
export function requests(ws, { purpose = "cleanup", candidates = false, since, refresh = true, now = new Date() } = {}) {
  if (!PURPOSES.includes(purpose)) throw new Error(ws.labels.messages["requests-for"])
  const where = conversationsOf(ws)
  if (!where) throw new Error(ws.labels.messages["requests-off"])
  return withRecords(ws, (db) => {
    if (refresh) collect(ws, db)
    const from = since ?? setting(db, "requests.marks")?.[purpose] ?? new Date(now.getTime() - FIRST_DAYS * 86400000).toISOString()
    const after = new Date(from).getTime()
    // Folders excluded after their requests were cached stay out too.
    const all = requestRecords(db, { after }).filter((row) => !skippedFolder(row.cwd, where.exclude)).sort(byTime)
    const until = all.at(-1)?.ts ?? null
    const places = placesOf(ws)
    const rows = all.filter((row) => !candidates || DURABLE.test(row.text)).map((row) => ({ ...shown(row), ...whereOf(row.cwd, places) }))
    if (until) setSetting(db, "requests.shown", { ...setting(db, "requests.shown"), [purpose]: until })
    return { purpose, since: new Date(after).toISOString(), until, candidates, rows }
  }, { write: true })
}

/** A cached row as a listing shows it: a pasted text by its length and its start. */
function shown({ pasted, ...row }) {
  if (!pasted) return row
  return { ...row, pasted: pasted.map((text) => {
    const chars = [...text]
    return { chars: chars.length, start: chars.length > PASTED_SHOWN ? `${chars.slice(0, PASTED_SHOWN).join("")}…` : text }
  }) }
}

/** Marks the requests up to `until` (default: the newest one the last listing for `purpose` considered) as read. */
export function markRequests(ws, purpose, { until } = {}) {
  if (!PURPOSES.includes(purpose)) throw new Error(ws.labels.messages["requests-for"])
  return withRecords(ws, (db) => {
    const mark = until ?? setting(db, "requests.shown")?.[purpose]
    if (!mark) throw new Error(format(ws.labels.messages["requests-mark-none"], { purpose }))
    setSetting(db, "requests.marks", { ...setting(db, "requests.marks"), [purpose]: mark })
    return mark
  }, { write: true })
}
