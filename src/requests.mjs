// The requests the owner typed to coding agents, read from the agents' local logs (Claude Code
// and Codex). A tidy-up reads the ones since the last tidy-up for work the owner handed out and
// decisions they made; the reflect skill reads them for lasting decisions. The logs are only read.
// The extracted text stays on this machine, in the workspace's records (records.mjs): never in the
// graph, never in git.
