/** A Korean particle follows the last Hangul syllable; other names use a colon. */
function withParticle(value, particle) {
  const text = String(value)
  const last = [...text.normalize("NFC")].at(-1)?.codePointAt(0)
  if (last < 0xac00 || last > 0xd7a3 || last === undefined) return `${text}:`
  const pair = ["이가", "은는", "을를", "과와"].find((one) => one.includes(particle))
  return text + pair[(last - 0xac00) % 28 === 0 ? 1 : 0]
}

/** Fills `{name}` placeholders, including a following Korean particle. */
export function format(template, values = {}) {
  return String(template).replace(/\{(\w+)\}([이가은는을를와과](?=\s|[.,!?]|$))?/g,
    (match, key, particle) => key in values ? particle ? withParticle(values[key], particle) : String(values[key]) : match)
}
